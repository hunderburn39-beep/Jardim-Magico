import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const url='http://127.0.0.1:8765/Strikers-1945/remake.html';
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:2,isMobile:true,hasTouch:true});
const exceptions=[];
page.on('pageerror',e=>exceptions.push(e.message));
await page.goto(url,{waitUntil:'load'});
await page.locator('#startBtn').waitFor({state:'visible'});
assert.equal(await page.locator('.planeCard').count(),4,'Deve haver quatro aviões');
await page.locator('.planeCard').nth(2).click();
await page.locator('#startBtn').click();
await page.waitForTimeout(700);
assert.equal(await page.locator('#pauseScreen').isVisible(),false,'Não deve arrancar em pausa');
const canvas=page.locator('canvas#game');
const r=await canvas.boundingBox();
assert(r && r.width>200,'Canvas deve ter tamanho responsivo');
await page.mouse.move(r.x+r.width*.5,r.y+r.height*.65);
await page.mouse.down();
await page.mouse.move(r.x+r.width*.5,r.y+r.height*.88,{steps:14});
await page.mouse.up();
await page.evaluate(()=>window.dispatchEvent(new Event('blur')));
await page.waitForTimeout(150);
assert.equal(await page.locator('#pauseScreen').isVisible(),false,'Arrastar para baixo / blur não pode pausar');
assert.equal(await page.locator('#pauseBtn').isVisible(),true,'Botão de pausa deve ficar disponível');
const bb=await page.locator('#bombBtn').boundingBox();
if(bb){await page.mouse.click(bb.x+bb.width/2,bb.y+bb.height/2);}
await page.waitForTimeout(200);
await page.screenshot({path:'strikers-v2-preview.png',fullPage:true});
await page.locator('#pauseBtn').click();
assert.equal(await page.locator('#pauseScreen').isVisible(),true,'O botão de pausa tem de funcionar');
await page.locator('#resumeBtn').click();
assert.equal(await page.locator('#pauseScreen').isVisible(),false,'O botão continuar tem de funcionar');
assert.deepEqual(exceptions,[],'Não pode haver exceções JavaScript');
await browser.close();
console.log('STRIKERS HTML5 V2: seleção, arrastar para baixo, blur sem pausa, bomba, pausa e retoma OK');
